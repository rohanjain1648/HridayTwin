"""
Causal physiology simulator for a synthetic hypertensive cohort.

Produces two data streams, as the challenge requires:
  1. Static / historical EHR (Synthea-style CSVs): demographics, diagnoses (SNOMED),
     lab history (LOINC), medications, genetic markers.
  2. Dynamic streams (hourly wearable + IoT + MyZenn app):
     heart rate, HRV (RMSSD), steps, stress score, sleep stages, home-cuff BP,
     smart-pillbox adherence, diet log, MyZenn mood check-ins and breathing sessions.

Plus a hidden ground-truth layer (never shown to the model):
  hourly ambulatory BP, the latent stress process, per-patient physiology parameters
  and the adverse events (hypertensive surges) derived from them.

BP is generated by a mechanistic model, so the "why" behind every surge is known:
  SBP(t) = base − meds·adherence + β·stress + γ·sleep_debt + salt_sens·salt_load
           + circadian (nocturnal dip, morning surge) + activity + noise

All data is synthetic. No real patient data is used (DPDP / HIPAA safe).

Usage:
    python -m twin_engine.simulator --patients 400 --days 60
"""

