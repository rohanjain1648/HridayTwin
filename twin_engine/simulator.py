@dataclass
class LatentParams:
    """Hidden physiology of one patient. Used only by the simulator and for validating the twin."""
    patient_id: str
    base_sbp: float          # untreated awake SBP at rest, no stress, no sleep debt
    med_effect: float        # mmHg lowered at full adherence
    stress_beta: float       # mmHg per unit of latent stress (0..1)
    sleep_gamma: float       # mmHg per hour of accumulated sleep debt
    salt_sens: float         # mmHg per g of acute excess salt load
    dip_frac: float          # nocturnal dip as fraction of SBP
    morning_surge: float     # mmHg added in the 2 h after waking
    dbp_offset: float
    hr_base: float
    hrv_base: float
    steps_base: float
    adherence_p: float
    stress_base: float
    dominant_driver: str = ""


def _logistic(x):
    return 1.0 / (1.0 + np.exp(-x))


def _gamma_kernel(dt_hours: np.ndarray, peak: float = 8.0) -> np.ndarray:
    """Salt-load response: rises to 1 at `peak` hours, decays over ~1.5 days."""
    x = np.clip(dt_hours, 0, None) / peak
    return np.where(dt_hours >= 0, x * np.exp(1 - x), 0.0)


def _ar1(rng, n, phi, sd):
    e = rng.normal(0, sd, n)
    out = np.empty(n)
    out[0] = e[0]
    for i in range(1, n):
        out[i] = phi * out[i - 1] + e[i]
    return out


def simulate_patient(idx: int, days: int, rng: np.random.Generator):
    pid = f"HT-{idx:04d}"
    H = days * 24
    hours = np.arange(H)
    hod = hours % 24
    day_of = hours // 24
    dow = (START.dayofweek + day_of) % 7
    weekend_h = dow >= 5

    # ── Static EHR ────────────────────────────────────────────────────
    sex = rng.choice(["M", "F"])
    age = int(np.clip(rng.normal(52, 11), 28, 80))
    height = rng.normal(168 if sex == "M" else 155, 6)
    bmi = float(np.clip(rng.normal(26.5, 4.2), 18, 42))
    weight = bmi * (height / 100) ** 2
    city, state, region = CITIES[rng.integers(len(CITIES))]
    tobacco = rng.random() < (0.22 if sex == "M" else 0.05)
    alcohol = rng.random() < (0.30 if sex == "M" else 0.06)
    diet = rng.choice(["Vegetarian", "Non-vegetarian", "Eggetarian"], p=[0.38, 0.52, 0.10])
    salt_g = float(np.clip(rng.normal(9.5, 2.2), 4.5, 16))
    occupation = OCCUPATIONS[rng.integers(len(OCCUPATIONS))]
    myzenn_user = rng.random() < 0.5

    dx = {"htn": True}
    dx["t2dm"] = rng.random() < _logistic(-2.2 + 0.05 * (age - 50) + 0.15 * (bmi - 26))
    dx["ckd"] = rng.random() < _logistic(-3.0 + 0.06 * (age - 50) + 1.0 * dx["t2dm"])
    dx["dyslipidemia"] = rng.random() < 0.45
    dx["osa"] = rng.random() < _logistic(-3.2 + 0.25 * (bmi - 26) + 0.8 * (sex == "M"))
    dx["anxiety"] = rng.random() < 0.18
    dx["depression"] = rng.random() < (0.12 + 0.2 * dx["anxiety"])
    dx["obesity"] = bmi >= 30
    dx["prior_mi"] = rng.random() < _logistic(-4.0 + 0.06 * (age - 50) + 0.8 * tobacco)
    dx["stroke"] = rng.random() < _logistic(-4.5 + 0.06 * (age - 50))

    genotypes = []
    risk_alleles_total = 0.0
    for gene, variant, rsid, freq, eff in GENES:
        n_risk = int(rng.binomial(2, freq))
        risk_alleles_total += n_risk * eff
        genotypes.append((gene, variant, rsid, n_risk))
    prs = float(rng.normal(0, 1))

    egfr = float(np.clip(rng.normal(95 - 0.7 * (age - 40) - 30 * dx["ckd"], 10), 18, 125))
    creat = float(np.clip((0.9 if sex == "M" else 0.7) * (egfr / 90) ** -0.9, 0.5, 4.5))
    hba1c = float(np.clip(rng.normal(8.0 if dx["t2dm"] else 5.5, 0.9 if dx["t2dm"] else 0.3), 4.6, 12.5))
    labs_now = {
        "hba1c": hba1c,
        "glucose": float(np.clip(28.7 * hba1c - 46.7 + rng.normal(0, 12), 70, 350)),
        "ldl": float(np.clip(rng.normal(135 if dx["dyslipidemia"] else 105, 25), 50, 240)),
        "hdl": float(np.clip(rng.normal(42 if sex == "M" else 50, 8), 22, 85)),
        "tg": float(np.clip(rng.lognormal(np.log(160 if dx["t2dm"] else 130), 0.3), 60, 600)),
        "creatinine": creat,
        "egfr": egfr,
        "sodium": float(np.clip(rng.normal(139, 2.2), 131, 147)),
        "potassium": float(np.clip(rng.normal(4.2, 0.35), 3.1, 5.6)),
        "uacr": float(np.clip(rng.lognormal(np.log(60 if dx["ckd"] or dx["t2dm"] else 12), 0.7), 2, 1500)),
        "tsh": float(np.clip(rng.lognormal(np.log(2.2), 0.4), 0.3, 9)),
    }

    # ── Latent physiology (hidden) ────────────────────────────────────
    base_sbp = (126 + 0.30 * (age - 50) + 0.8 * (bmi - 26) + 4.0 * dx["ckd"] + 2.5 * dx["t2dm"]
                + 2.2 * prs + risk_alleles_total + 0.9 * (salt_g - 9.5) + 2.0 * tobacco + 1.5 * alcohol
                + rng.normal(0, 6))
    n_meds = int(np.clip(1 + (base_sbp > 150) + (base_sbp > 160) + (rng.random() < 0.2), 1, 4))
    drugs = [BP_DRUGS[i] for i in rng.choice(len(BP_DRUGS), n_meds, replace=False)]
    med_effect = float(sum(d[2] for d in drugs) * rng.uniform(0.75, 1.25))
    # Latent sensitivities, loosely conditioned on the EHR so the static stream is informative
    stress_beta = float(rng.lognormal(np.log(18 + 10 * dx["anxiety"] + 4 * (age < 45)), 0.35))
    sleep_gamma = float(rng.lognormal(np.log(1.5 + 1.0 * dx["osa"]), 0.3))
    agt_tt = genotypes[0][3] == 2
    salt_sens = float(rng.lognormal(np.log(0.9 + 0.5 * agt_tt + 0.6 * dx["ckd"] + 0.01 * (age - 50)), 0.35))
    non_dipper = rng.random() < (0.15 + 0.35 * (dx["osa"] or dx["ckd"] or dx["t2dm"]))
    dip_frac = float(rng.uniform(0.0, 0.05) if non_dipper else rng.uniform(0.08, 0.16))

    lp = LatentParams(
        patient_id=pid,
        base_sbp=float(base_sbp),
        med_effect=med_effect,
        stress_beta=stress_beta,
        sleep_gamma=sleep_gamma,
        salt_sens=salt_sens,
        dip_frac=dip_frac,
        morning_surge=float(rng.uniform(4, 18) + 4 * (age > 60)),
        dbp_offset=float(rng.uniform(10, 20)),
        hr_base=float(np.clip(rng.normal(72 - 0.05 * (age - 50), 6), 55, 92)),
        hrv_base=float(np.clip(rng.normal(48 - 0.55 * (age - 30), 8), 14, 80)),
        steps_base=float(np.clip(rng.lognormal(np.log(6000), 0.35), 1500, 14000)),
        adherence_p=float(np.clip(rng.beta(8, 1.6), 0.45, 0.99)),
        stress_base=float(rng.uniform(0.12, 0.32) + 0.08 * dx["anxiety"]),
    )

    # ── Latent stress process (hourly) ────────────────────────────────
    episode_env = np.zeros(H)
    h = int(rng.integers(0, 72))
    while h < H:
        if rng.random() < 1 / 10:  # a stress episode (deadline, family issue, travel...)
            ramp = int(rng.integers(18, 40))       # slow build-up: this is what makes early warning possible
            plateau = int(rng.integers(24, 96))
            decay = int(rng.integers(12, 36))
            amp = rng.uniform(0.25, 0.6)
            env = np.concatenate([np.linspace(0, 1, ramp), np.ones(plateau), np.linspace(1, 0, decay)]) * amp
            end = min(H, h + len(env))
            episode_env[h:end] = np.maximum(episode_env[h:end], env[: end - h])
            h = end + int(rng.integers(24, 96))
        else:
            h += 24
    work_bump = np.where((~weekend_h) & (hod >= 9) & (hod < 19) & (occupation not in ("Retired", "Homemaker")), 0.08, 0.0)
    stress = lp.stress_base + episode_env + work_bump + _ar1(rng, H, 0.9, 0.025)

    # MyZenn breathing / meditation sessions: relieve stress, raise HRV, acutely lower BP
    session_min = np.zeros(H)
    relief = np.zeros(H)
    for d in range(days):
        daily_stress = stress[d * 24 + 9: d * 24 + 21].mean()
        p = (0.25 + 0.5 * (daily_stress > 0.45)) if myzenn_user else 0.02
        if rng.random() < p:
            hr_at = d * 24 + int(rng.choice([7, 13, 21]))
            mins = float(rng.choice([5, 10, 15]))
            session_min[hr_at] = mins
            k = np.arange(0, min(14, H - hr_at))
            relief[hr_at + k] += 0.07 * (mins / 10) * np.exp(-k / 6)
    stress = np.clip(stress - relief, 0, 1)

    # ── Sleep (nightly) ───────────────────────────────────────────────
    asleep = np.zeros(H, dtype=bool)
    sleep_rows = []
    debt = np.zeros(days)
    running = 0.0
    for d in range(days):
        eve = min(H - 1, d * 24 + 21)
        s_ex = max(0.0, stress[eve] - lp.stress_base)
        weekend_night = ((START.dayofweek + d) % 7) >= 4  # Fri/Sat nights
        sleep_h = float(np.clip(rng.normal(7.0 + 0.5 * weekend_night - 2.4 * s_ex - 0.6 * dx["osa"], 0.5), 3.5, 9.5))
        awake_min = float(np.clip(18 + 70 * s_ex + 25 * dx["osa"] + rng.normal(0, 8), 5, 150))
        bed = 22.5 + rng.normal(0, 0.5) + 0.8 * weekend_night + 0.6 * s_ex
        wake = bed + sleep_h + awake_min / 60
        b0, w0 = int(round(d * 24 + bed)), int(round(d * 24 + wake))
        asleep[max(0, b0): min(H, w0)] = True
        deep = float(np.clip(rng.normal(18 - 14 * s_ex - 4 * dx["osa"] - 0.08 * (age - 50), 2.5), 4, 28))
        rem = float(np.clip(rng.normal(22 - 7 * s_ex, 2.5), 8, 30))
        running = 0.7 * running + max(0.0, 7.5 - sleep_h)
        if d + 1 < days:
            debt[d + 1] = running
        sleep_rows.append({
            "patient_id": pid,
            "date": (START + pd.Timedelta(days=d + 1)).date(),  # night ending on the morning of day d+1
            "bedtime": (START + pd.Timedelta(hours=d * 24 + bed)).floor("min"),
            "waketime": (START + pd.Timedelta(hours=d * 24 + wake)).floor("min"),
            "total_sleep_h": round(sleep_h, 2),
            "awake_min": round(awake_min, 1),
            "deep_pct": round(deep, 1),
            "rem_pct": round(rem, 1),
            "light_pct": round(100 - deep - rem, 1),
            "sleep_efficiency": round(100 * sleep_h / (sleep_h + awake_min / 60), 1),
            "_wake_hour": w0,
        })
    sleep_df = pd.DataFrame(sleep_rows)
    wake_hours = sleep_df["_wake_hour"].to_numpy()
    debt_h = np.repeat(debt, 24)

    # ── Medication adherence (smart pillbox) ──────────────────────────
    taken = np.zeros(days)
    gap_left = 0
    for d in range(days):
        if gap_left == 0 and rng.random() < 1 / 22:  # ran out of refill / travelling / forgot
            gap_left = int(rng.integers(2, 6))
        p = 0.12 if gap_left > 0 else lp.adherence_p
        taken[d] = rng.random() < p
        gap_left = max(0, gap_left - 1)
    level = np.zeros(days)
    lvl = lp.adherence_p
    for d in range(days):
        lvl = 0.5 * lvl + 0.5 * taken[d]
        level[d] = lvl
    med_level_h = np.repeat(level, 24)

    # ── Salt load (festival meals, restaurant, pickles) ───────────────
    salt_events = []
    for d in range(days):
        wk = ((START.dayofweek + d) % 7) >= 5
        if rng.random() < (0.10 + 0.06 * wk):
            salt_events.append((d * 24 + 20, float(rng.uniform(4, 9))))
    salt_load = np.zeros(H)
    for t0, g in salt_events:
        salt_load += g * _gamma_kernel(hours - t0)

    # ── Activity ──────────────────────────────────────────────────────
    profile = np.array([0, 0, 0, 0, 0, 0, .3, 1.2, 1.0, .6, .5, .5, .8, 1.0, .5, .5, .6, .9, 1.2, 1.0, .6, .3, .1, 0])
    steps = np.zeros(H)
    for d in range(days):
        sl = slice(d * 24, d * 24 + 24)
        s_ex = max(0.0, stress[sl].mean() - lp.stress_base)
        wk = ((START.dayofweek + d) % 7) >= 5
        total = lp.steps_base * (1 - 0.4 * s_ex) * (0.85 if wk else 1.0) * rng.lognormal(0, 0.25)
        prof = profile * rng.uniform(0.6, 1.4, 24) * (~asleep[sl])
        steps[sl] = total * prof / max(prof.sum(), 1e-6)

    # ── Circadian BP pattern ──────────────────────────────────────────
    circ = 3.0 * np.sin(2 * np.pi * (hod - 10) / 24)
    circ = np.where(asleep, -lp.dip_frac * lp.base_sbp, circ)
    for w in wake_hours:
        for k in range(3):
            if 0 <= w + k < H:
                circ[w + k] += lp.morning_surge * (1 - k / 3)
    session_acute = np.zeros(H)
    for t0 in np.nonzero(session_min)[0]:
        session_acute[t0: t0 + 3] += 4.0

    # ── Ground-truth ambulatory BP ────────────────────────────────────
    awake_debt = np.where(asleep, 0.3, 1.0) * debt_h
    sbp = (lp.base_sbp - lp.med_effect * med_level_h + lp.stress_beta * stress + lp.sleep_gamma * awake_debt
           + lp.salt_sens * salt_load + circ + 0.0012 * steps - session_acute + _ar1(rng, H, 0.6, 3.0))
    dbp = 0.5 * sbp + lp.dbp_offset + rng.normal(0, 2.5, H)

    # ── Wearable signals (what a smartwatch actually sees) ────────────
    hr = (lp.hr_base + 16 * (stress - 0.2) + 7 * steps / 1000 - 9 * asleep + 0.6 * debt_h
          + rng.normal(0, 3, H))
    hrv = (lp.hrv_base * (1 - 0.7 * (stress - 0.2)) * np.where(asleep, 1.18, 1.0) - 0.9 * debt_h
           + 60 * relief + rng.normal(0, 4, H))
    hrv = np.clip(hrv, 6, 160)
    stress_score = np.clip(100 * (1 - hrv / (lp.hrv_base * 1.35)) + 0.4 * (hr - lp.hr_base) + rng.normal(0, 6, H), 1, 99)
    worn = rng.random(H) > 0.05
    for d in range(days):  # daily charging gap
        c = d * 24 + int(rng.integers(8, 20))
        worn[c: c + 1] = False

    ts = START + pd.to_timedelta(hours, unit="h")
    hourly = pd.DataFrame({
        "patient_id": pid,
        "ts": ts,
        "heart_rate": np.where(worn, np.round(hr, 1), np.nan),
        "hrv_rmssd": np.where(worn, np.round(hrv, 1), np.nan),
        "steps": np.where(worn, np.round(steps), np.nan),
        "stress_score": np.where(worn, np.round(stress_score, 1), np.nan),
        "asleep": asleep.astype(int),
        "myzenn_session_min": session_min,
    })

    # Home BP cuff (Omron-style): morning + evening, often skipped
    cuff_rows = []
    for d in range(days):
        for hh, p in ((7, 0.72), (20, 0.58)):
            if rng.random() < p:
                t0 = d * 24 + hh
                s = sbp[t0] + rng.normal(0, 5)
                cuff_rows.append({"patient_id": pid, "ts": ts[t0] + pd.Timedelta(minutes=int(rng.integers(0, 50))),
                                  "sbp": round(s), "dbp": round(dbp[t0] + rng.normal(0, 4)),
                                  "pulse": round(hr[t0] + rng.normal(0, 3))})
    cuff = pd.DataFrame(cuff_rows)

    pill = pd.DataFrame({"patient_id": pid, "date": [(START + pd.Timedelta(days=d)).date() for d in range(days)],
                         "dose_taken": taken.astype(int)})
    diet_log = pd.DataFrame([{"patient_id": pid, "ts": ts[t0], "salty_meal": 1, "est_extra_salt_g": round(g, 1)}
                         for t0, g in salt_events if rng.random() < 0.65],
                        columns=["patient_id", "ts", "salty_meal", "est_extra_salt_g"])

    mood_rows = []
    for d in range(days):
        if rng.random() < (0.8 if myzenn_user else 0.35):
            ds = stress[d * 24 + 9: d * 24 + 21].mean()
            mood_rows.append({"patient_id": pid, "ts": ts[d * 24 + 21],
                              "mood_score": int(np.clip(round(8.8 - 9 * ds + rng.normal(0, 0.9)), 1, 10))})
    mood = pd.DataFrame(mood_rows, columns=["patient_id", "ts", "mood_score"])

    truth = pd.DataFrame({"patient_id": pid, "ts": ts, "sbp": np.round(sbp, 1), "dbp": np.round(dbp, 1),
                          "latent_stress": np.round(stress, 3), "med_level": np.round(med_level_h, 3),
                          "salt_load_g": np.round(salt_load, 2), "sleep_debt_h": np.round(debt_h, 2)})

    # ── Adverse events: sustained stage-2 BP ──────────────────────────
    flag = (sbp >= SURGE_SBP) | (dbp >= SURGE_DBP)
    events = []
    i = 0
    while i < H:
        if flag[i]:
            j = i
            while j < H and flag[j]:
                j += 1
            if j - i >= SURGE_MIN_HOURS:
                seg = slice(i, j)
                contrib = {
                    "stress": lp.stress_beta * (stress[seg].mean() - lp.stress_base),
                    "sleep_debt": lp.sleep_gamma * awake_debt[seg].mean(),
                    "salt": lp.salt_sens * salt_load[seg].mean(),
                    "missed_meds": lp.med_effect * (lp.adherence_p - med_level_h[seg].mean()),
                }
                events.append({"patient_id": pid, "onset": ts[i], "onset_hour": i, "duration_h": j - i,
                               "peak_sbp": round(float(sbp[seg].max()), 1), "peak_dbp": round(float(dbp[seg].max()), 1),
                               "crisis": bool(sbp[seg].max() >= CRISIS_SBP),
                               "primary_driver": max(contrib, key=contrib.get)})
            i = j
        else:
            i += 1
    events_df = pd.DataFrame(events, columns=["patient_id", "onset", "onset_hour", "duration_h", "peak_sbp",
                                              "peak_dbp", "crisis", "primary_driver"])
    if len(events_df):
        lp.dominant_driver = events_df["primary_driver"].mode().iloc[0]

    # ── EHR tables ────────────────────────────────────────────────────
    first = (FIRST_M if sex == "M" else FIRST_F)[rng.integers(20)]
    birth = (START - pd.Timedelta(days=int(age * 365.25 + rng.integers(0, 365)))).date()
    office = lp.base_sbp - lp.med_effect * lp.adherence_p + lp.stress_beta * lp.stress_base + rng.normal(6, 5)  # white-coat bump
    patient = {
        "Id": pid, "BIRTHDATE": birth, "FIRST": first, "LAST": LAST[rng.integers(len(LAST))], "GENDER": sex,
        "AGE": age, "CITY": city, "STATE": state, "REGION": region, "OCCUPATION": occupation,
        "HEIGHT_CM": round(height, 1), "WEIGHT_KG": round(weight, 1), "BMI": round(bmi, 1),
        "TOBACCO": int(tobacco), "ALCOHOL": int(alcohol), "DIET": diet, "SALT_G_DAY": round(salt_g, 1),
        "OFFICE_SBP": round(office), "OFFICE_DBP": round(0.5 * office + lp.dbp_offset + rng.normal(0, 3)),
        "MYZENN_USER": int(myzenn_user), "SYNTHETIC": 1,
    }
    conditions = []
    for key, present in dx.items():
        if present:
            code, desc = SNOMED[key]
            onset_years = rng.uniform(0.5, 12) if key != "htn" else rng.uniform(1, 15)
            conditions.append({"PATIENT": pid, "START": (START - pd.Timedelta(days=int(365 * onset_years))).date(),
                               "CODE": code, "SYSTEM": "SNOMED-CT", "DESCRIPTION": desc})
    observations = []
    for months_ago in (24, 12, 3):  # lab history with gentle drift
        date = (START - pd.Timedelta(days=30 * months_ago)).date()
        drift = months_ago / 24
        for key, val in labs_now.items():
            code, desc, unit = LOINC[key]
            v = val * (1 - 0.04 * drift * (key in ("hba1c", "ldl", "creatinine", "uacr"))) \
                * (1 + 0.04 * drift * (key == "egfr")) * rng.normal(1, 0.03)
            observations.append({"PATIENT": pid, "DATE": date, "CODE": code, "SYSTEM": "LOINC",
                                 "DESCRIPTION": desc, "VALUE": round(float(v), 2), "UNITS": unit})
        osbp = office + rng.normal(4 * drift, 6)
        for key, v in (("sbp", osbp), ("dbp", 0.5 * osbp + lp.dbp_offset), ("bmi", bmi * rng.normal(1 - 0.01 * drift, 0.01))):
            code, desc, unit = LOINC[key]
            observations.append({"PATIENT": pid, "DATE": date, "CODE": code, "SYSTEM": "LOINC",
                                 "DESCRIPTION": desc, "VALUE": round(float(v), 1), "UNITS": unit})
    meds = [{"PATIENT": pid, "START": (START - pd.Timedelta(days=int(rng.integers(60, 2000)))).date(), "STOP": None,
             "DESCRIPTION": name, "CLASS": cls, "INDICATION": "Essential hypertension"} for name, cls, _ in drugs]
    if dx["t2dm"]:
        meds.append({"PATIENT": pid, "START": (START - pd.Timedelta(days=int(rng.integers(60, 2000)))).date(),
                     "STOP": None, "DESCRIPTION": "Metformin 500 mg tablet", "CLASS": "Biguanide",
                     "INDICATION": "Diabetes mellitus type 2"})
    if dx["dyslipidemia"] or dx["prior_mi"]:
        meds.append({"PATIENT": pid, "START": (START - pd.Timedelta(days=int(rng.integers(60, 2000)))).date(),
                     "STOP": None, "DESCRIPTION": "Atorvastatin 20 mg tablet", "CLASS": "Statin",
                     "INDICATION": "Hyperlipidemia"})
    genomics = [{"PATIENT": pid, "GENE": g, "VARIANT": v, "RSID": rs, "RISK_ALLELES": n,
                 "GENOTYPE": ["non-risk/non-risk", "risk/non-risk", "risk/risk"][n]} for g, v, rs, n in genotypes]
    genomics.append({"PATIENT": pid, "GENE": "PRS", "VARIANT": "BP polygenic risk score (z)", "RSID": None,
                     "RISK_ALLELES": round(prs, 2), "GENOTYPE": None})

    return {
        "patients": [patient], "conditions": conditions, "observations": observations,
        "medications": meds, "genomics": genomics,
        "hourly": hourly, "sleep": sleep_df.drop(columns="_wake_hour"), "cuff": cuff, "pillbox": pill,
        "diet": diet_log, "mood": mood, "truth": truth, "events": events_df, "latent": [asdict(lp)],
    }


def generate(n_patients: int = 400, days: int = 60, seed: int = SEED) -> dict[str, pd.DataFrame]:
    rng = np.random.default_rng(seed)
    parts: dict[str, list] = {}
    for i in range(1, n_patients + 1):
        out = simulate_patient(i, days, rng)
        for k, v in out.items():
            parts.setdefault(k, []).append(v if isinstance(v, pd.DataFrame) else pd.DataFrame(v))
    return {k: pd.concat(v, ignore_index=True) for k, v in parts.items()}


def save(tables: dict[str, pd.DataFrame]) -> None:
    for d in (EHR_DIR, STREAM_DIR, TRUTH_DIR):
        d.mkdir(parents=True, exist_ok=True)
    for k in ("patients", "conditions", "observations", "medications", "genomics"):
        tables[k].to_csv(EHR_DIR / f"{k}.csv", index=False)
    for k in ("hourly", "sleep", "cuff", "pillbox", "diet", "mood"):
        tables[k].to_parquet(STREAM_DIR / f"{k}.parquet", index=False)
    tables["truth"].to_parquet(TRUTH_DIR / "abpm_hourly.parquet", index=False)
    tables["events"].to_csv(TRUTH_DIR / "events.csv", index=False)
    tables["latent"].to_csv(TRUTH_DIR / "latent_params.csv", index=False)


def main():
    ap = argparse.ArgumentParser(description="Generate the synthetic HridayTwin cohort")
    ap.add_argument("--patients", type=int, default=400)
    ap.add_argument("--days", type=int, default=60)
    ap.add_argument("--seed", type=int, default=SEED)
    args = ap.parse_args()
    tables = generate(args.patients, args.days, args.seed)
    save(tables)
    ev = tables["events"]
    n_pd = args.patients * args.days
    print(f"Patients: {args.patients} | days: {args.days} | hourly rows: {len(tables['hourly']):,}")
    print(f"Surge events: {len(ev):,} ({len(ev) / n_pd:.3f} per patient-day), "
          f"patients with >=1 event: {ev['patient_id'].nunique()}, crises: {int(ev['crisis'].sum())}")
    if len(ev):
        print("Primary drivers:", ev["primary_driver"].value_counts().to_dict())


if __name__ == "__main__":
    main()
